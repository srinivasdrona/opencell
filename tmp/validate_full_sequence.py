HALF_MASK = 0xFFFF
HALF_SIGN = 0x8000
XOR_MASK = 0x80008000

def encode(raw):
    lo = raw & HALF_MASK
    hi = (raw >> 16) & HALF_MASK
    enc = (lo << 16) | hi
    if lo & HALF_SIGN:
        enc ^= XOR_MASK
    return enc

def decode(enc):
    if enc & HALF_SIGN:
        enc ^= XOR_MASK
    lo = enc & HALF_MASK
    hi = (enc >> 16) & HALF_MASK
    return (lo << 16) | hi

